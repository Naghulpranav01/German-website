// Helper to look up any lesson by level and id
export function getLessonById(level: CEFRLevel, lessonId: string): Lesson | undefined {
  if (level === 'A1') {
    return A1_LESSONS.find((l) => l.id === lessonId);
  }
  if (level === 'A2') {
    for (const m of A2_MODULES) {
      const match = m.lessons.find((l) => l.id === lessonId);
      if (match) return match;
    }
  }
  if (level === 'B1') {
    for (const m of B1_MODULES) {
      const match = m.lessons.find((l) => l.id === lessonId);
      if (match) return match;
    }
  }
  if (level === 'B2') {
    for (const m of B2_MODULES) {
      const match = m.lessons.find((l) => l.id === lessonId);
      if (match) return match;
    }
  }
  if (level === 'C1') {
    for (const m of C1_MODULES) {
      const match = m.lessons.find((l) => l.id === lessonId);
      if (match) return match;
    }
  }
  return undefined;
}
